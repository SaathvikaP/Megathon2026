// Generates the idempotent content seed migration from backend/content.
// Usage: npm run db:seed-sql
//
// The generated SQL only inserts rows that do not exist yet (ON CONFLICT DO NOTHING),
// so it never overwrites edits made later through the admin interface.
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PILLARS } from '../../frontend/src/lib/content/pillars.mjs';
import { LESSONS } from '../content/lessons.mjs';
import { QUIZZES, QUESTIONS } from '../content/money-quest.mjs';
import { COMICS } from '../content/comics.mjs';
import { validateContent } from './content-validation.mjs';

const here = dirname(fileURLToPath(import.meta.url));
export const SEED_PATH = resolve(here, '../supabase/migrations/20261011000700_seed_learning_content.sql');

const lit = (value) => {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  return `'${String(value).replace(/'/g, "''")}'`;
};
const json = (value) => `${lit(JSON.stringify(value))}::jsonb`;
const textArray = (items) => `array[${items.map(lit).join(', ')}]::text[]`;

export function buildSeedSql() {
  validateContent({ PILLARS, LESSONS, QUIZZES, QUESTIONS, COMICS });

  const out = [];
  out.push('-- GENERATED by scripts/build-seed.mjs from /content. Do not edit by hand.');
  out.push('-- Idempotent: inserts only missing rows and never overwrites admin edits.');
  out.push('');

  out.push('-- Learning pillars');
  for (const p of PILLARS) {
    out.push(
      `insert into public.learning_pillars (slug, title, tagline, description, icon, sort_order) values (` +
        [p.slug, p.title, p.tagline, p.description, p.icon, p.sort_order].map(lit).join(', ') +
        `) on conflict (slug) do nothing;`,
    );
  }
  out.push('');

  out.push('-- Lessons');
  for (const l of LESSONS) {
    out.push(
      `insert into public.lessons (pillar_id, slug, title, summary, difficulty, learning_objectives, content, estimated_minutes, is_published, sort_order, source_references)\n` +
        `select p.id, ${lit(l.slug)}, ${lit(l.title)}, ${lit(l.summary)}, ${lit(l.difficulty)}, ${textArray(l.learning_objectives)}, ` +
        `${json(l.content)}, ${l.estimated_minutes}, true, ${l.sort_order}, ${json(l.source_references)}\n` +
        `from public.learning_pillars p where p.slug = ${lit(l.pillar)}\n` +
        `on conflict (slug) do nothing;`,
    );
  }
  out.push('');

  out.push('-- Money Quest levels');
  for (const z of QUIZZES) {
    out.push(
      `insert into public.quizzes (slug, title, level, description, pass_correct_threshold, is_published) values (` +
        [z.slug, z.title, z.level, z.description, z.pass_correct_threshold, true].map(lit).join(', ') +
        `) on conflict (slug) do nothing;`,
    );
  }
  out.push('');

  const insertQuestion = (q, { kind, sortOrder, parentSlug, quizSlug, lessonSlug, base }) => {
    out.push(
      `insert into public.quiz_questions (quiz_id, kind, parent_question_id, slug, title, prompt, topic, difficulty, concept, misconception, lesson_id, sort_order, is_published, source_references)\n` +
        `select z.id, ${lit(kind)}, ${parentSlug ? `(select id from public.quiz_questions where slug = ${lit(parentSlug)})` : 'null'}, ` +
        `${lit(q.slug)}, ${lit(q.title)}, ${lit(q.prompt)}, ${lit(base.topic)}, ${lit(base.difficulty)}, ${lit(base.concept)}, ${lit(base.misconception)}, ` +
        `(select id from public.lessons where slug = ${lit(lessonSlug)}), ${sortOrder}, true, ${json(base.references)}\n` +
        `from public.quizzes z where z.slug = ${lit(quizSlug)}\n` +
        `on conflict (slug) do nothing;`,
    );
    const values = q.options.map((o, i) => `(${lit(o.key)}, ${lit(o.text)}, ${i + 1})`).join(',\n  ');
    out.push(
      `insert into public.quiz_options (question_id, option_key, option_text, sort_order)\n` +
        `select q.id, v.option_key, v.option_text, v.sort_order\n` +
        `from public.quiz_questions q\ncross join (values\n  ${values}\n) as v(option_key, option_text, sort_order)\n` +
        `where q.slug = ${lit(q.slug)}\n` +
        `on conflict (question_id, option_key) do nothing;`,
    );
    out.push(
      `insert into public.quiz_answer_keys (question_id, correct_option_id, explanation, teaching_point)\n` +
        `select q.id, o.id, ${lit(q.explanation)}, ${lit(q.teaching_point)}\n` +
        `from public.quiz_questions q join public.quiz_options o on o.question_id = q.id and o.option_key = ${lit(q.correct)}\n` +
        `where q.slug = ${lit(q.slug)}\n` +
        `on conflict (question_id) do nothing;`,
    );
  };

  out.push('-- Money Quest questions, options and answer keys');
  const orderWithinQuiz = new Map();
  for (const q of QUESTIONS) {
    const n = (orderWithinQuiz.get(q.quiz) ?? 0) + 1;
    orderWithinQuiz.set(q.quiz, n);
    out.push(`-- Question ${q.number}: ${q.title}`);
    insertQuestion(q, { kind: 'core', sortOrder: n, parentSlug: null, quizSlug: q.quiz, lessonSlug: q.lesson, base: q });
    insertQuestion(q.practice, { kind: 'practice', sortOrder: n, parentSlug: q.slug, quizSlug: q.quiz, lessonSlug: q.lesson, base: q });
    out.push('');
  }

  out.push('-- Remediation comic scripts (drafts awaiting admin review; not published)');
  for (const c of COMICS) {
    const q = QUESTIONS.find((x) => x.slug === c.question);
    const script = { characters: c.characters, panels: c.panels };
    out.push(
      `insert into public.remediation_comics (question_id, lesson_id, slug, title, description, topic, concept, misconception, script, takeaway, alt_text, source_references, provider, generation_status, review_status)\n` +
        `select q.id, q.lesson_id, ${lit(c.slug)}, ${lit(c.title)}, ${lit(`Remediation for question ${q.number}: ${q.title}`)}, ${lit(q.topic)}, ${lit(c.concept)}, ${lit(q.misconception)}, ` +
        `${json(script)}, ${lit(c.takeaway)}, ${lit(c.alt_text)}, ${json(c.references)}, 'comicsmaker_manual', 'script_ready', 'in_review'\n` +
        `from public.quiz_questions q where q.slug = ${lit(c.question)}\n` +
        `on conflict (slug) do nothing;`,
    );
  }
  out.push('');

  return out.join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(SEED_PATH, buildSeedSql(), 'utf8');
  console.log(`Wrote ${SEED_PATH}`);
}
